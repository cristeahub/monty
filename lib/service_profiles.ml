(* The service profile configuration Monty generates itself when no trusted
   configuration was saved with `monty service start --config FILE`. One
   profile per native account directory whose CLI is on PATH: the default
   Codex, Claude and Pi homes plus each Mantle profile's Codex and Claude
   homes, so `mantle work` followed by plain `monty` selects `claude-work`.
   Every profile allows the Monty home, the `wt` worktree root and all
   registered project repos as workspace roots. The file is rewritten on each
   service start Monty owns, so projects registered later become allowed roots
   without manual edits. *)
open Conversation_store

let path ~home = file home [ "service-profiles.json" ]

let user_home () =
  match Sys.getenv_opt "HOME" with Some home when String.trim home <> "" -> Some home | _ -> None

let is_directory path = Sys.file_exists path && Sys.is_directory path

(* (profile id, harness, account directory) for every account present on disk. *)
let accounts () =
  match user_home () with
  | None -> []
  | Some user_home ->
      let harnesses = [ ("codex", ".codex"); ("claude", ".claude"); ("pi", ".pi/agent") ] in
      let native = List.map (fun (harness, dir) -> (harness, harness, Filename.concat user_home dir)) harnesses in
      (* Mantle keeps `<profile>/codex` and `<profile>/claude` under this root. *)
      let mantle_root = Filename.concat user_home ".local/share/mantle/profiles" in
      let mantle_profiles =
        if is_directory mantle_root then Sys.readdir mantle_root |> Array.to_list |> List.sort compare else []
      in
      let mantle =
        List.concat_map
          (fun name ->
            List.map
              (fun harness -> (harness ^ "-" ^ name, harness, Filename.concat (Filename.concat mantle_root name) harness))
              [ "codex"; "claude" ])
          mantle_profiles
      in
      List.filter (fun (_, _, dir) -> is_directory dir) (native @ mantle)

let roots ~home =
  let projects = get (Project_storage.load_projects ~home) in
  let worktrees = Option.map (fun user_home -> Filename.concat user_home ".local/share/wt") (user_home ()) in
  (home :: Option.to_list worktrees) @ List.map (fun (project : Overview_types.project) -> project.repo) projects
  |> List.filter is_directory |> List.sort_uniq String.compare

let profile ~home ~roots (id, harness, directory) =
  Option.map
    (fun command ->
      let account_key = match harness with "codex" -> "codex_home" | "claude" -> "claude_home" | _ -> "pi_home" in
      (* The Claude bridge needs the SDK's Python; prefer the runtime Monty
         keeps. A venv's python is a symlink, so this path is not symlink-checked. *)
      let python = List.fold_left Filename.concat home [ ".monty"; "runtime"; "claude-sdk"; "bin"; "python" ] in
      let python = if harness = "claude" && Sys.file_exists python then [ ("python", string python) ] else [] in
      obj
        ([ ("id", string id); ("harness", string harness); ("command", string command); (account_key, string directory);
           ("roots", `List (List.map string roots)) ]
        @ python))
    (Process.command_exists harness)

(* Writes the generated configuration and returns its path. *)
let generate ~home =
  let roots = roots ~home in
  let profiles = List.filter_map (profile ~home ~roots) (accounts ()) in
  if profiles = [] then
    fail 503
      "Monty client service is not running and no native account directory (~/.codex, ~/.claude or ~/.pi/agent) with its CLI on PATH was found to generate a configuration; run monty service start --config FILE";
  let note =
    "Generated by Monty on every service start from the native account directories it finds and the registered projects; edits are overwritten. Pass --config FILE to monty service start for a hand-maintained configuration."
  in
  let path = path ~home in
  locked home (fun () -> get (State_store.write_json_atomic ~path (obj [ ("note", string note); ("profiles", `List profiles) ])));
  path
